"""Generate the dashboard's TypeScript types from the API's OpenAPI schema.

    python scripts/gen_api_types.py           # rewrite web/src/api/schema.ts
    python scripts/gen_api_types.py --check   # exit 1 if the file is out of date

The dashboard never declares API shapes by hand: every type in ``schema.ts`` comes from
the Pydantic models the server actually returns, and a test fails if the two drift apart.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

from sift.api.app import create_app
from sift.core.config import SiftConfig
from sift.core.service import SiftService

TARGET = Path(__file__).resolve().parent.parent / "web" / "src" / "api" / "schema.ts"

HEADER = """\
// Generated by scripts/gen_api_types.py from the FastAPI OpenAPI schema.
// Do not edit by hand - change the Python models and regenerate.
"""


def _name(raw: str) -> str:
    """``SiftConfig-Output`` -> ``SiftConfigOutput``."""
    return re.sub(r"[^0-9A-Za-z_]", "", raw)


def _wrap(type_text: str) -> str:
    return f"({type_text})" if " | " in type_text else type_text


def ts_type(schema: dict[str, Any], indent: str = "") -> str:
    if "$ref" in schema:
        return _name(schema["$ref"].rsplit("/", 1)[-1])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(ts_type(option, indent) for option in schema[key]))
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(item, indent) for item in schema["prefixItems"]) + "]"
        return _wrap(ts_type(schema.get("items", {}), indent)) + "[]"
    if kind == "object" or "properties" in schema:
        if "properties" in schema:
            return _object(schema, indent)
        extra = schema.get("additionalProperties")
        value = ts_type(extra, indent) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def _object(schema: dict[str, Any], indent: str, *, request: bool = False) -> str:
    # Responses always carry every field, whatever its default, so only request bodies
    # have optional properties.
    required = set(schema.get("required", [])) if request else set(schema["properties"])
    inner = indent + "  "
    lines = ["{"]
    for field, spec in schema["properties"].items():
        mark = "" if field in required else "?"
        description = spec.get("description")
        if description:
            first = " ".join(description.split())
            lines.append(f"{inner}/** {first} */")
        lines.append(f"{inner}{field}{mark}: {ts_type(spec, inner)};")
    lines.append(indent + "}")
    return "\n".join(lines)


def render() -> str:
    """The full text of ``schema.ts`` for the API as it is right now."""
    app = create_app(SiftService(SiftConfig(), history_file=Path("unused")))
    document = app.openapi()
    components = document["components"]["schemas"]
    requests = {
        content["schema"]["$ref"].rsplit("/", 1)[-1]
        for path in document["paths"].values()
        for operation in path.values()
        for content in operation.get("requestBody", {}).get("content", {}).values()
        if "$ref" in content.get("schema", {})
    }
    skipped = {"HTTPValidationError", "ValidationError"}
    blocks = [HEADER]
    for raw in sorted(components):
        if raw in skipped:
            continue
        schema = components[raw]
        name = _name(raw)
        if "properties" in schema:
            body = _object(schema, "", request=raw in requests)
            blocks.append(f"export interface {name} {body}\n")
        else:
            blocks.append(f"export type {name} = {ts_type(schema)};\n")
    return "\n".join(blocks)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if schema.ts is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is out of date; run scripts/gen_api_types.py", file=sys.stderr)
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
