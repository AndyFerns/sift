"""Ecosystem-neutral artifacts: coverage reports and ``dist/`` output."""

from __future__ import annotations

from sift.core.detectors.base import Candidate, Detector, Rule
from sift.core.detectors.python import MANIFESTS as PYTHON_MANIFESTS
from sift.core.models import Confidence, Ecosystem, Evidence

_PROJECT_MANIFESTS = (
    "package.json",
    "pyproject.toml",
    "setup.py",
    "setup.cfg",
    "Cargo.toml",
    "go.mod",
    "pom.xml",
)

_SQLITE_MAGIC = b"SQLite format 3\x00"


def _is_coverage_database(candidate: Candidate) -> Evidence | None:
    """coverage.py stores its data file as a SQLite database."""
    try:
        with open(candidate.path, "rb") as handle:
            header = handle.read(len(_SQLITE_MAGIC))
    except OSError:
        return None
    if header != _SQLITE_MAGIC:
        return None
    return Evidence(kind="marker", detail="is a coverage.py data file", path=candidate.path)


DETECTOR = Detector(
    name="general",
    ecosystem=Ecosystem.GENERAL,
    rules=(
        Rule(
            id="general.coverage",
            names=("coverage",),
            ecosystem=Ecosystem.GENERAL,
            category="coverage",
            description="Coverage report (regenerated by running tests with coverage)",
            manifests=_PROJECT_MANIFESTS,
            markers=(
                "lcov.info",
                "lcov-report",
                "coverage-final.json",
                "coverage-summary.json",
                "clover.xml",
                "cobertura-coverage.xml",
            ),
            # "coverage" is also a perfectly good name for a source package.
            manifest_only=Confidence.LOW,
        ),
        Rule(
            id="general.coverage-data",
            names=(".coverage",),
            kind="file",
            ecosystem=Ecosystem.GENERAL,
            category="coverage",
            description="coverage.py data file",
            manifests=(*PYTHON_MANIFESTS, ".coveragerc"),
            check=_is_coverage_database,
            distinctive=True,
        ),
        Rule(
            id="general.dist",
            names=("dist",),
            ecosystem=Ecosystem.GENERAL,
            category="build-output",
            description="Distribution output (rebuilt by your build or packaging command)",
            manifests=_PROJECT_MANIFESTS,
            marker_suffixes=(".whl", ".tar.gz"),
            # dist/ is sometimes committed on purpose (GitHub Actions, published bundles),
            # so a manifest next door is not enough to call it safe to delete.
            manifest_only=Confidence.LOW,
            marker_only=None,
        ),
    ),
)
