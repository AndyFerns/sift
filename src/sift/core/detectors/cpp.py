"""C/C++: CMake build trees."""

from __future__ import annotations

from sift.core.detectors.base import Detector, Rule
from sift.core.models import Confidence, Ecosystem

_BUILD_MARKERS = ("CMakeCache.txt", "CMakeFiles", "cmake_install.cmake", "build.ninja")

DETECTOR = Detector(
    name="cpp",
    ecosystem=Ecosystem.CPP,
    rules=(
        Rule(
            id="cpp.build",
            names=("build",),
            ecosystem=Ecosystem.CPP,
            category="build-output",
            description="CMake build tree (regenerated by configuring and building again)",
            manifests=("CMakeLists.txt",),
            markers=_BUILD_MARKERS,
            # Plenty of projects keep hand-written files in build/. Without CMake's own
            # files inside, a CMakeLists.txt next door is only a hint.
            manifest_only=Confidence.LOW,
        ),
        Rule(
            id="cpp.cmake-build",
            names=("cmake-build-debug", "cmake-build-release"),
            ecosystem=Ecosystem.CPP,
            category="build-output",
            description="CLion/CMake build tree",
            manifests=("CMakeLists.txt",),
            markers=_BUILD_MARKERS,
            distinctive=True,
        ),
        Rule(
            id="cpp.cmakefiles",
            names=("CMakeFiles",),
            ecosystem=Ecosystem.CPP,
            category="build-output",
            description="CMake generated files from an in-source build",
            manifests=("CMakeCache.txt", "CMakeLists.txt"),
            markers=(
                "CMakeConfigureLog.yaml",
                "CMakeOutput.log",
                "cmake.check_cache",
                "TargetDirectories.txt",
                "pkgRedirects",
            ),
            distinctive=True,
        ),
    ),
)
